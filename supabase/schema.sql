-- ADAZ private cloud snapshot and AI usage limit
-- Run this file in Supabase Dashboard > SQL Editor.
create table if not exists public.adaz_snapshots (
  user_id uuid primary key references auth.users(id) on delete cascade,
  payload jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.adaz_snapshots enable row level security;
drop policy if exists "Users can read their own ADAZ snapshot" on public.adaz_snapshots;
create policy "Users can read their own ADAZ snapshot" on public.adaz_snapshots for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users can insert their own ADAZ snapshot" on public.adaz_snapshots;
create policy "Users can insert their own ADAZ snapshot" on public.adaz_snapshots for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users can update their own ADAZ snapshot" on public.adaz_snapshots;
create policy "Users can update their own ADAZ snapshot" on public.adaz_snapshots for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Users can delete their own ADAZ snapshot" on public.adaz_snapshots;
create policy "Users can delete their own ADAZ snapshot" on public.adaz_snapshots for delete to authenticated using ((select auth.uid()) = user_id);
grant select, insert, update, delete on public.adaz_snapshots to authenticated;
revoke all on public.adaz_snapshots from anon;
create table if not exists public.adaz_ai_usage (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create index if not exists adaz_ai_usage_user_created_idx on public.adaz_ai_usage (user_id, created_at desc);
alter table public.adaz_ai_usage enable row level security;
-- No policies for browser users: service_role access is server-only in the Edge Function.
revoke all on public.adaz_ai_usage from anon, authenticated;
